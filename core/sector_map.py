def get_sector(ticker):
    """Returns the real sector for a ticker if we have it curated,
    otherwise UNKNOWN - callers should treat UNKNOWN as "don't apply
    the sector cap to this one, we genuinely don't know."""

    clean = ticker.upper().strip()
    if not clean.endswith(".NS"):
        clean += ".NS"

    entry = UNIVERSE.get(clean)
    return entry["sector"] if entry else "UNKNOWN"
